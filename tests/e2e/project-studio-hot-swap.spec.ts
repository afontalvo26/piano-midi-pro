import { expect, test } from "@playwright/test";

test("editar pasos MIDI mientras suena el beat conserva transporte y aplica revisión futura", async ({ page }) => {
  page.setDefaultTimeout(20_000);
  await page.setViewportSize({ width: 320, height: 760 });
  await page.goto("/");
  await page.getByRole("button", { name: "Nuevo proyecto" }).click();
  const tempo = page.getByRole("spinbutton", { name: "Tempo inicial del proyecto" });
  await tempo.fill("60");
  await tempo.blur();
  await page.getByRole("button", { name: "Batería", exact: true }).click();
  await page.getByRole("button", { name: "Preparar batería" }).click();
  const rack = page.getByRole("region", { name: "Rack de batería de 16 pads" });
  const kick1 = rack.getByRole("button", { name: /Kick, paso 1,/ });
  const kick2 = rack.getByRole("button", { name: /Kick, paso 2,/ });
  await expect(kick1).toBeEnabled({ timeout: 20_000 });
  await kick1.click();
  await page.getByRole("button", { name: "Reproducir" }).click();
  await expect(page.getByRole("button", { name: "Pausar" })).toBeVisible({ timeout: 20_000 });
  const projectBar = page.getByRole("region", { name: "Proyecto de Beatmaker" });
  const readTick = async () => Number((await projectBar.textContent())?.match(/tick (\d+)/)?.[1] ?? 0);
  await expect.poll(readTick).toBeGreaterThan(0);
  const before = await readTick();
  await page.getByRole("button", { name: "Mezclador" }).click();
  const mixer = page.getByRole("region", { name: "Mezclador del proyecto" });
  const drums = mixer.getByRole("region", { name: "Canal Batería grabada" });
  await drums.getByRole("spinbutton", { name: "Ganancia (dB)" }).fill("-6");
  await drums.getByRole("spinbutton", { name: "Ganancia (dB)" }).blur();
  await mixer.getByRole("spinbutton", { name: "Ganancia master (dB)" }).fill("-3");
  await mixer.getByRole("spinbutton", { name: "Ganancia master (dB)" }).blur();
  await expect(page.getByRole("button", { name: "Pausar" })).toBeVisible();
  await page.getByRole("button", { name: "Batería", exact: true }).click();
  await expect(kick2).toBeEnabled();
  await kick2.click();
  await expect(rack.getByText("2 golpes", { exact: false })).toBeVisible();
  await expect(page.getByRole("button", { name: "Pausar" })).toBeVisible();
  await expect(projectBar).toContainText("Edición MIDI aplicada sin detener el beat");
  await expect.poll(readTick).toBeGreaterThanOrEqual(before);
  await page.getByRole("button", { name: "Detener" }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
